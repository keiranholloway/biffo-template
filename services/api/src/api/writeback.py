"""Executing an agent run's write-back (ADR-0027 §2, §5, §7).

This is the security-critical half of write-back, and its shape is deliberate:
**the orchestrator triggers, Core decides and executes.** The internal route that
calls in here is handed an agent-run id and nothing else. Target table, operation,
column set, values, row selection and the principal to act as are all resolved
here from state Core already holds, so a buggy or compromised plugin cannot name
a table, pick a column, supply a value or choose an identity.

That hardens by one step the rule ``owner_data_handlers`` already follows for
ADR-0017 §5 — *the owner is taken from the verified token, never from the
request* — because an asynchronous completion has no live token to forward at
all. Hence the stored principal, and hence :func:`bind_principal_session`.

Ordering matters and is not incidental:

1. an ungranted target is **404**, indistinguishable from one that does not
   exist (ADR-0004 §4), so a workflow cannot probe what else is writeable;
2. the run is **claimed** before anything is written, so a redelivered
   completion event cannot double-write;
3. the session is **bound to the stored author** before the statement, and a
   refusal aborts — the write never runs on an unbound session;
4. every refusal is **recorded**, because a denial nobody can see is
   indistinguishable from a feature that silently stopped working.
"""

